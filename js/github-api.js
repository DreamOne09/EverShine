/**
 * GitHub API 輔助函式
 * 用於會員資料的讀取和生成更新 Issue
 */

class GitHubAPI {
    constructor(config) {
        this.config = config;
        // 使用公開 API URL
        this.apiUrl = `${config.apiUrl}/repos/${config.owner}/${config.repo}/contents/${config.filePath}`;
    }

    /**
     * 獲取檔案內容 (公開讀取)
     */
    async getFileContent() {
        try {
            const headers = {
                'Accept': 'application/vnd.github.v3+json'
            };

            // 如果有 Token 且不是預設值，才使用 Token (用於測試或私有 Repo)
            if (this.config.token && this.config.token !== 'YOUR_GITHUB_TOKEN_HERE') {
                headers['Authorization'] = `token ${this.config.token}`;
            }

            const response = await fetch(this.apiUrl, { headers });

            if (!response.ok) {
                throw new Error(`GitHub API 錯誤: ${response.status}`);
            }

            const data = await response.json();
            const content = decodeURIComponent(escape(atob(data.content))); // 正確處理 UTF-8
            return {
                content: JSON.parse(content),
                sha: data.sha
            };
        } catch (error) {
            console.error('獲取檔案失敗:', error);
            throw error;
        }
    }

    /**
     * 驗證 PIN 碼
     */
    async verifyPin(memberName, pin) {
        try {
            const { content } = await this.getFileContent();
            const member = content.members.find(m => m.name === memberName);

            if (!member) {
                throw new Error('找不到此會員');
            }

            // 計算 PIN 碼的 SHA-256 雜湊值
            const pinHash = await this.hashPin(pin);

            if (pinHash !== member.pinHash) {
                throw new Error('PIN 碼錯誤');
            }

            return member;
        } catch (error) {
            console.error('驗證失敗:', error);
            throw error;
        }
    }

    /**
     * 生成更新資料的 Issue URL
     */
    async generateUpdateIssueUrl(memberName, pin, newData) {
        try {
            // 1. 驗證 PIN 碼 (確保是本人操作)
            await this.verifyPin(memberName, pin);

            // 2. 準備 Issue 內容
            const title = `Update member: ${memberName}`;
            const body = `
### Member Update Request

**Member:** ${memberName}
**Timestamp:** ${new Date().toISOString()}

\`\`\`json
${JSON.stringify(newData, null, 2)}
\`\`\`

---
*This issue was automatically generated by the EverShine Member Edit System.*
`;

            // 3. 生成 URL
            const issueUrl = `https://github.com/${this.config.owner}/${this.config.repo}/issues/new?title=${encodeURIComponent(title)}&body=${encodeURIComponent(body)}&labels=member-update`;

            return issueUrl;
        } catch (error) {
            console.error('生成 Issue URL 失敗:', error);
            throw error;
        }
    }

    /**
     * 計算 PIN 碼的 SHA-256 雜湊值
     */
    async hashPin(pin) {
        const encoder = new TextEncoder();
        const data = encoder.encode(pin);
        const hashBuffer = await crypto.subtle.digest('SHA-256', data);
        const hashArray = Array.from(new Uint8Array(hashBuffer));
        return hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
    }
}

// 匯出到全域
if (typeof window !== 'undefined') {
    window.GitHubAPI = GitHubAPI;
}
